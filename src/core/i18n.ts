/**
 * Exported so tests can assert coverage directly. `translate` falls back to
 * English before giving up, which is right at runtime but hides a missing
 * Russian string — the only way to catch one is to look in the dictionary.
 */
export const DICTS: Record<Locale, Dict> = { en: EN, ru: RU };

/** Resolve the effective locale from an explicit language + Obsidian's setting. */
export function resolveLocale(language: ZenithLanguage): Locale {
    if (language === 'en' || language === 'ru') return language;
    // 'auto' → follow Obsidian. It stores the UI language under localStorage.
    const obsidian = window.localStorage.getItem('language') ?? 'en';
    return obsidian.startsWith('ru') ? 'ru' : 'en';
}

/** Values substituted into `{placeholders}` in a string. */
export type TParams = Record<string, string | number>;

function interpolate(text: string, params?: TParams): string {
    if (!params) return text;
    return text.replace(/\{(\w+)\}/g, (whole, name: string) =>
        name in params ? String(params[name]) : whole
    );
}

/**
 * Which plural form a count takes.
 *
 * English has two (one / other); Russian has three, and picking between them is
 * not a matter of taste — "9 элементов" vs "2 элемента" vs "1 элемент" are all
 * required. Getting this wrong is the tell-tale sign of a machine-translated
 * interface, so counts go through here rather than through string concatenation.
 */
export function pluralForm(locale: Locale, count: number): 'one' | 'few' | 'many' | 'other' {
    const n = Math.abs(Math.round(count));
    if (locale === 'ru') {
        const mod10 = n % 10;
        const mod100 = n % 100;
        if (mod10 === 1 && mod100 !== 11) return 'one';
        if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return 'few';
        return 'many';
    }
    return n === 1 ? 'one' : 'other';
}

/** Translate a key for a locale, falling back to English then the key itself. */
export function translate(locale: Locale, key: string, params?: TParams): string {
    const text = DICTS[locale][key] ?? EN[key] ?? key;
    return interpolate(text, params);
}

/**
 * Translate a counted noun: looks up `<key>.<form>` and passes `count` through
 * as a placeholder, so a string can read "{count} items" / "{count} элемента".
 */
export function translatePlural(locale: Locale, key: string, count: number, params?: TParams): string {
    const form = pluralForm(locale, count);
    const dict = DICTS[locale];
    const candidate = `${key}.${form}`;
    // `other` is the English catch-all; Russian keys that only define `many`
    // still resolve through the English fallback inside `translate`.
    const resolved = dict[candidate] !== undefined ? candidate : `${key}.other`;
    return translate(locale, resolved, { count, ...params });
}

export interface Translator {
    (key: string, params?: TParams): string;
    /** Counted noun — picks the right plural form for the locale. */
    plural: (key: string, count: number, params?: TParams) => string;
    locale: Locale;
}

/**
 * React hook returning a `t()` bound to the current language. Re-renders when
 * the user changes the language in settings.
 */
export function useTranslation(): Translator {
    const language = useZenithStore((s) => s.settings.language);
    const locale = resolveLocale(language);
    return useMemo(() => {
        const t = ((key: string, params?: TParams) => translate(locale, key, params)) as Translator;
        t.plural = (key, count, params) => translatePlural(locale, key, count, params);
        t.locale = locale;
        return t;
    }, [locale]);
}
